#!/usr/bin/env python3
"""Turn tokens.json into the files the app and the admin use.

    python3 replica/design/build_tokens.py            # writes next to tokens.json
    python3 replica/design/build_tokens.py --out app/  # or into the Expo project

Writes:
  global.css          NativeWind v4: CSS variables for light (:root) and dark (.dark)
  tokens.css          the same variables for the web admin and the preview page
  tailwind.tokens.js  theme extension: bg-surface, text-muted, rounded-md, ...
  tokens.ts           typed values for places Tailwind can't reach
                      (navigation theme, status bar, charts, animations)

tokens.json stays the only place a colour is written. Never edit the outputs.
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def rgb_triplet(hex_):
    h = hex_.lstrip("#")
    return "%d %d %d" % (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def css_vars(colors, indent="  "):
    return "\n".join("%s--color-%s: %s;" % (indent, k, rgb_triplet(v)) for k, v in colors.items())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokens", default=os.path.join(HERE, "tokens.json"))
    ap.add_argument("--out", default=HERE)
    a = ap.parse_args()
    t = json.load(open(a.tokens, encoding="utf-8"))
    light, dark = t["color"]["light"], t["color"]["dark"]
    assert light.keys() == dark.keys(), "light and dark must have the same roles"
    os.makedirs(a.out, exist_ok=True)
    banner = "/* generated by build_tokens.py from tokens.json: do not edit */\n"

    # NativeWind v4 reads CSS variables from global.css; `dark:` and the
    # system colour scheme switch the .dark block.
    open(os.path.join(a.out, "global.css"), "w").write(
        banner + "@tailwind base;\n@tailwind components;\n@tailwind utilities;\n\n"
        ":root {\n%s\n}\n\n.dark {\n%s\n}\n" % (css_vars(light), css_vars(dark)))

    open(os.path.join(a.out, "tokens.css"), "w").write(
        banner + ":root {\n%s\n}\n\n@media (prefers-color-scheme: dark) {\n"
        "  :root:not([data-theme=\"light\"]) {\n%s\n  }\n}\n\n:root[data-theme=\"dark\"] {\n%s\n}\n"
        % (css_vars(light), css_vars(dark, "    "), css_vars(dark)))

    colors = {k: "rgb(var(--color-%s) / <alpha-value>)" % k for k in light}
    fonts = t["font"]
    theme = {
        "colors": colors,
        "fontFamily": {
            "sans": [fonts["sans"]],
            "display": [fonts["display"]],
            "arabic": [fonts["arabic"]],
        },
        "fontSize": {k: [str(v["size"]) + "px", {"lineHeight": str(v["line"]) + "px",
                                                  "fontWeight": str(v["weight"])}]
                     for k, v in t["type"].items()},
        "spacing": {str(i): str(v) + "px" for i, v in enumerate(t["space"])},
        "borderRadius": {k: str(v) + "px" for k, v in t["radius"].items()},
    }
    open(os.path.join(a.out, "tailwind.tokens.js"), "w").write(
        "// generated by build_tokens.py from tokens.json: do not edit\n"
        "// use in tailwind.config.js: theme: { extend: require('./tailwind.tokens') }\n"
        "module.exports = %s;\n" % json.dumps(theme, indent=2))

    ts = {
        "color": {"light": light, "dark": dark},
        "type": t["type"], "space": t["space"], "radius": t["radius"],
        "shadow": t["shadow"], "motion": t["motion"], "layout": t["layout"],
        "font": {k: v for k, v in fonts.items() if not k.startswith("_")},
    }
    open(os.path.join(a.out, "tokens.ts"), "w").write(
        "// generated by build_tokens.py from tokens.json: do not edit\n"
        "export const tokens = %s as const;\n\n"
        "export type ColorRole = keyof typeof tokens.color.light;\n" % json.dumps(ts, indent=2))

    print("wrote global.css, tokens.css, tailwind.tokens.js, tokens.ts to %s" % a.out)


if __name__ == "__main__":
    main()
